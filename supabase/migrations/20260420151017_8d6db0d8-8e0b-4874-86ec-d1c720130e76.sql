-- Trigger-Funktion neu: prüft gegen offizielle Liste
CREATE OR REPLACE FUNCTION public.auto_archive_non_zh()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  IF NEW.archived_at IS NULL 
     AND (
       NEW.postal_code IS NULL 
       OR NOT EXISTS (SELECT 1 FROM public.zh_postal_codes WHERE postal_code = NEW.postal_code)
     ) THEN
    NEW.archived_at = now();
  END IF;
  RETURN NEW;
END;
$$;